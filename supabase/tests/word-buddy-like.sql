-- Stand-in for Word Buddy living in the same Supabase project (tests only). It has the
-- parts that could clash with the Recipe App: a "profiles" table with other columns, a
-- "sync_profile" function, and its own trigger on auth.users. Modelled on
-- word-buddy/supabase/schema.sql.
create table public.words (id bigint generated by default as identity primary key, word text);
create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  email text,
  language text,
  last_sign_in_at timestamptz,
  sign_in_count int not null default 0
);
create table public.sign_ins (user_id uuid, signed_in_at timestamptz);

create or replace function public.sync_profile() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  new_sign_in boolean := new.last_sign_in_at is not null
    and (tg_op = 'INSERT' or new.last_sign_in_at is distinct from old.last_sign_in_at);
begin
  insert into public.profiles as p (id, email, language, last_sign_in_at, sign_in_count)
  values (new.id, new.email, coalesce(new.raw_user_meta_data->>'language', 'nl'), new.last_sign_in_at,
          case when new_sign_in then 1 else 0 end)
  on conflict (id) do update set email = excluded.email, last_sign_in_at = excluded.last_sign_in_at,
    sign_in_count = p.sign_in_count + case when new_sign_in then 1 else 0 end;
  if new_sign_in then
    insert into public.sign_ins (user_id, signed_in_at) values (new.id, new.last_sign_in_at);
  end if;
  return new;
end;
$$;
create trigger on_auth_user_changed after insert or update on auth.users
  for each row execute function public.sync_profile();
