-- Recipe App database for Supabase.
-- Run all of this in Supabase: SQL Editor -> New query -> paste -> Run.
-- Safe to run again after an update: it adds what is new and keeps your data.
--
-- Every user sees and changes only their own recipes and groups. The rules below
-- (Row Level Security) are enforced by the database itself, whatever the app does.
-- Sign-up and passwords are handled by Supabase Auth; the display name lives in the
-- user's metadata ("username").

-- ---------- Tables ----------

create table if not exists public.recipes (
  id                bigint generated by default as identity primary key,
  user_id           uuid not null default auth.uid() references auth.users (id) on delete cascade,
  title             text not null check (btrim(title) <> ''),
  description       text,
  instructions      text,
  prep_time_minutes integer check (prep_time_minutes > 0),
  cook_time_minutes integer check (cook_time_minutes > 0),
  servings          integer check (servings > 0),
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now()
);
create index if not exists recipes_user_id_idx on public.recipes (user_id);

create table if not exists public.recipe_ingredients (
  id        bigint generated by default as identity primary key,
  recipe_id bigint not null references public.recipes (id) on delete cascade,
  position  integer not null default 0,
  name      text not null check (btrim(name) <> ''),
  quantity  text,
  unit      text
);
create index if not exists recipe_ingredients_recipe_id_idx on public.recipe_ingredients (recipe_id, position);

create table if not exists public.recipe_groups (
  id          bigint generated by default as identity primary key,
  user_id     uuid not null default auth.uid() references auth.users (id) on delete cascade,
  name        text not null check (btrim(name) <> ''),
  description text,
  created_at  timestamptz not null default now()
);
create index if not exists recipe_groups_user_id_idx on public.recipe_groups (user_id);

create table if not exists public.recipe_group_items (
  group_id  bigint not null references public.recipe_groups (id) on delete cascade,
  recipe_id bigint not null references public.recipes (id) on delete cascade,
  added_at  timestamptz not null default now(),
  primary key (group_id, recipe_id)
);
create index if not exists recipe_group_items_recipe_id_idx on public.recipe_group_items (recipe_id);

-- ---------- Who may do what ----------
-- Signed-out visitors (anon) get nothing; signed-in users (authenticated) only their own rows.

revoke all on public.recipes, public.recipe_ingredients, public.recipe_groups, public.recipe_group_items from anon;
grant select, insert, update, delete
  on public.recipes, public.recipe_ingredients, public.recipe_groups, public.recipe_group_items to authenticated;

alter table public.recipes            enable row level security;
alter table public.recipe_ingredients enable row level security;
alter table public.recipe_groups      enable row level security;
alter table public.recipe_group_items enable row level security;

drop policy if exists "own recipes" on public.recipes;
create policy "own recipes" on public.recipes for all to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

drop policy if exists "ingredients of own recipes" on public.recipe_ingredients;
create policy "ingredients of own recipes" on public.recipe_ingredients for all to authenticated
  using (exists (select 1 from public.recipes r where r.id = recipe_id and r.user_id = (select auth.uid())))
  with check (exists (select 1 from public.recipes r where r.id = recipe_id and r.user_id = (select auth.uid())));

drop policy if exists "own groups" on public.recipe_groups;
create policy "own groups" on public.recipe_groups for all to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

-- A group may only hold recipes of the same user.
drop policy if exists "items of own groups" on public.recipe_group_items;
create policy "items of own groups" on public.recipe_group_items for all to authenticated
  using (exists (select 1 from public.recipe_groups g where g.id = group_id and g.user_id = (select auth.uid())))
  with check (
    exists (select 1 from public.recipe_groups g where g.id = group_id and g.user_id = (select auth.uid()))
    and exists (select 1 from public.recipes r where r.id = recipe_id and r.user_id = (select auth.uid()))
  );

-- ---------- Saving a recipe with its ingredients in one step ----------
-- The app calls: supabase.rpc('save_recipe', {'recipe': {...}}). Returns the recipe id.
-- Runs with the caller's rights, so the rules above still apply.

create or replace function public.save_recipe(recipe jsonb)
returns bigint
language plpgsql
security invoker
set search_path = ''
as $$
declare
  rid bigint := nullif(recipe ->> 'id', '')::bigint;
begin
  if rid is null then
    insert into public.recipes (title, description, instructions, prep_time_minutes, cook_time_minutes, servings)
    values (
      recipe ->> 'title',
      nullif(btrim(recipe ->> 'description'), ''),
      nullif(btrim(recipe ->> 'instructions'), ''),
      (recipe ->> 'prep_time_minutes')::integer,
      (recipe ->> 'cook_time_minutes')::integer,
      (recipe ->> 'servings')::integer
    )
    returning id into rid;
  else
    update public.recipes set
      title             = recipe ->> 'title',
      description       = nullif(btrim(recipe ->> 'description'), ''),
      instructions      = nullif(btrim(recipe ->> 'instructions'), ''),
      prep_time_minutes = (recipe ->> 'prep_time_minutes')::integer,
      cook_time_minutes = (recipe ->> 'cook_time_minutes')::integer,
      servings          = (recipe ->> 'servings')::integer,
      updated_at        = now()
    where id = rid;
    if not found then
      raise exception 'Recipe not found.' using errcode = 'P0002';
    end if;
    delete from public.recipe_ingredients where recipe_id = rid;
  end if;

  insert into public.recipe_ingredients (recipe_id, position, name, quantity, unit)
  select rid, (i.ord - 1)::integer, btrim(i.item ->> 'name'),
         nullif(btrim(i.item ->> 'quantity'), ''), nullif(btrim(i.item ->> 'unit'), '')
  from jsonb_array_elements(coalesce(recipe -> 'ingredients', '[]'::jsonb)) with ordinality as i (item, ord)
  where btrim(coalesce(i.item ->> 'name', '')) <> '';

  return rid;
end;
$$;

revoke execute on function public.save_recipe(jsonb) from public, anon;
grant execute on function public.save_recipe(jsonb) to authenticated;

-- ---------- Keep-alive ----------
-- A free Supabase project pauses after about a week without activity.
-- A daily GitHub Action calls this (it reads no data).

create or replace function public.ping()
returns text
language sql
stable
set search_path = ''
as $$ select 'ok'::text $$;

grant execute on function public.ping() to anon, authenticated;
