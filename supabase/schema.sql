-- Recipe App database for Supabase.
-- Run all of this in Supabase: SQL Editor -> New query -> paste -> Run.
-- Safe to run again after an update: it adds what is new and keeps your data.
--
-- Every user sees and changes only their own recipes and groups. The rules below
-- (Row Level Security) are enforced by the database itself, whatever the app does.
-- Sign-up and passwords are handled by Supabase Auth; the display name lives in the
-- user's metadata ("first_name", "last_name").

-- ---------- Tables ----------

create table if not exists public.recipes (
  id                bigint generated by default as identity primary key,
  user_id           uuid not null default auth.uid() references auth.users (id) on delete cascade,
  title             text not null check (btrim(title) <> ''),
  description       text,
  instructions      text,
  prep_time_minutes integer check (prep_time_minutes > 0),
  cook_time_minutes integer check (cook_time_minutes > 0),
  servings          integer check (servings > 0),
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now()
);
create index if not exists recipes_user_id_idx on public.recipes (user_id);

create table if not exists public.recipe_ingredients (
  id        bigint generated by default as identity primary key,
  recipe_id bigint not null references public.recipes (id) on delete cascade,
  position  integer not null default 0,
  name      text not null check (btrim(name) <> ''),
  quantity  text,
  unit      text
);
create index if not exists recipe_ingredients_recipe_id_idx on public.recipe_ingredients (recipe_id, position);

create table if not exists public.recipe_groups (
  id          bigint generated by default as identity primary key,
  user_id     uuid not null default auth.uid() references auth.users (id) on delete cascade,
  name        text not null check (btrim(name) <> ''),
  description text,
  created_at  timestamptz not null default now()
);
create index if not exists recipe_groups_user_id_idx on public.recipe_groups (user_id);

create table if not exists public.recipe_group_items (
  group_id  bigint not null references public.recipe_groups (id) on delete cascade,
  recipe_id bigint not null references public.recipes (id) on delete cascade,
  added_at  timestamptz not null default now(),
  primary key (group_id, recipe_id)
);
create index if not exists recipe_group_items_recipe_id_idx on public.recipe_group_items (recipe_id);

-- ---------- Living next to Word Buddy ----------
-- This project may also hold Word Buddy, which has its own "profiles" table and
-- "sync_profile" function. The Recipe App therefore uses recipe_profiles and
-- sync_recipe_profile. An earlier version of this file used the old names; this block
-- cleans that up, and stops if that earlier run overwrote Word Buddy's function.
do $$
begin
  if exists (
    select 1 from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public' and p.proname = 'sync_profile'
      and pg_get_functiondef(p.oid) like '%display_name%'
  ) then
    if to_regclass('public.words') is not null then
      raise exception using
        message = 'An earlier Recipe App setup replaced Word Buddy''s sync_profile function, so sign-ups and sign-ins can fail.',
        hint = 'Run word-buddy/supabase/schema.sql once to restore it, then run this file again.';
    end if;
    -- No Word Buddy here: it was only the Recipe App's own old function.
    drop trigger if exists sync_profile on auth.users;
    drop function public.sync_profile();
  end if;
end $$;
-- An earlier Recipe App setup could have added this trigger; Word Buddy's is on_auth_user_changed.
drop trigger if exists sync_profile on auth.users;

-- ---------- Profiles: the name friends see ----------
-- (recipe_profiles, so it never clashes with Word Buddy's "profiles" in a shared project.)
-- One row per account, kept in sync with Supabase Auth by a trigger. The email is used
-- to match friend requests; only you, your friends and people whose request is waiting
-- for you can read your profile.

create table if not exists public.recipe_profiles (
  id           uuid primary key references auth.users (id) on delete cascade,
  display_name text not null default '',
  email        text not null default '',
  created_at   timestamptz not null default now()
);

-- The name friends see: "First Last" from the account settings, else the older single
-- "username", else the part of the email before the @. At most 60 characters.
create or replace function public.display_name_of(meta jsonb, email text)
returns text language sql immutable set search_path = ''
as $$
  select left(coalesce(
    nullif(btrim(concat_ws(' ', nullif(btrim(meta ->> 'first_name'), ''), nullif(btrim(meta ->> 'last_name'), ''))), ''),
    nullif(btrim(meta ->> 'username'), ''),
    split_part(coalesce(email, ''), '@', 1)
  ), 60)
$$;

create or replace function public.sync_recipe_profile()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.recipe_profiles (id, display_name, email)
  values (
    new.id,
    public.display_name_of(new.raw_user_meta_data, new.email),
    lower(coalesce(new.email, ''))
  )
  on conflict (id) do update
    set display_name = excluded.display_name,
        email = excluded.email;
  return new;
end;
$$;

drop trigger if exists sync_recipe_profile on auth.users;
create trigger sync_recipe_profile
  after insert or update of email, raw_user_meta_data on auth.users
  for each row execute function public.sync_recipe_profile();

-- Accounts made before this existed get their profile now.
insert into public.recipe_profiles (id, display_name, email)
select u.id,
       public.display_name_of(u.raw_user_meta_data, u.email),
       lower(coalesce(u.email, ''))
from auth.users u
on conflict (id) do nothing;

-- Lets the app show the owner's name next to a shared recipe or collection.
do $$ begin
  if not exists (select 1 from pg_constraint where conname = 'recipes_owner_profile_fkey') then
    alter table public.recipes add constraint recipes_owner_profile_fkey
      foreign key (user_id) references public.recipe_profiles (id) on delete cascade;
  end if;
  if not exists (select 1 from pg_constraint where conname = 'recipe_groups_owner_profile_fkey') then
    alter table public.recipe_groups add constraint recipe_groups_owner_profile_fkey
      foreign key (user_id) references public.recipe_profiles (id) on delete cascade;
  end if;
end $$;

-- ---------- Friends ----------
-- Find people by name or email with search_people() (names plus a hidden email such as
-- "an***@gmail.com", never full addresses), or send a request to a full email address.
-- A request is addressed to an email address, not to an account. Sending by email never
-- says whether that address has an account: the app always says "Request sent", and
-- someone who signs up later with that address finds the request waiting.
-- A request only exists while it waits; accepting turns it into a friendship and
-- declining or cancelling deletes it.

create table if not exists public.friend_requests (
  id         bigint generated by default as identity primary key,
  from_user  uuid not null default auth.uid() references public.recipe_profiles (id) on delete cascade,
  to_email   text not null check (to_email = lower(btrim(to_email)) and to_email like '%_@_%'),
  created_at timestamptz not null default now(),
  unique (from_user, to_email)
);
create index if not exists friend_requests_to_email_idx on public.friend_requests (to_email);
-- Set when the request was made by picking someone from the search (see list_sent_requests).
alter table public.friend_requests add column if not exists to_user uuid references public.recipe_profiles (id) on delete cascade;

-- How often someone searched or sent requests recently, to stop spam and scraping.
-- Only the functions use it; nobody can read or write it directly.
create table if not exists public.rate_events (
  user_id uuid not null references auth.users (id) on delete cascade,
  kind    text not null,
  at      timestamptz not null default now()
);
create index if not exists rate_events_user_kind_at_idx on public.rate_events (user_id, kind, at);
alter table public.rate_events enable row level security;
revoke all on public.rate_events from anon, authenticated;

-- One row per pair of friends, the smaller id first.
create table if not exists public.friendships (
  user_a     uuid not null references public.recipe_profiles (id) on delete cascade,
  user_b     uuid not null references public.recipe_profiles (id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_a, user_b),
  check (user_a < user_b)
);
create index if not exists friendships_user_b_idx on public.friendships (user_b);

-- ---------- Sharing ----------
-- Share one recipe, or a whole collection (which includes recipes added to it later).
-- Friends can read what is shared with them; only the owner can ever change it.

create table if not exists public.recipe_shares (
  recipe_id  bigint not null references public.recipes (id) on delete cascade,
  friend_id  uuid not null references public.recipe_profiles (id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (recipe_id, friend_id)
);
create index if not exists recipe_shares_friend_id_idx on public.recipe_shares (friend_id);

create table if not exists public.collection_shares (
  group_id   bigint not null references public.recipe_groups (id) on delete cascade,
  friend_id  uuid not null references public.recipe_profiles (id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (group_id, friend_id)
);
create index if not exists collection_shares_friend_id_idx on public.collection_shares (friend_id);

-- ---------- Helper checks used by the access rules ----------
-- These run with the definer's rights so the rules can look at other tables without
-- the rules of those tables looping back (which Postgres would refuse). Each one only
-- answers yes or no about the signed-in user.

create or replace function public.my_email()
returns text language sql stable set search_path = ''
as $$ select lower(coalesce(auth.jwt() ->> 'email', '')) $$;

create or replace function public.is_friend(other uuid)
returns boolean language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.friendships f
    where f.user_a = least(auth.uid(), other) and f.user_b = greatest(auth.uid(), other)
  )
$$;

create or replace function public.owns_recipe(rid bigint)
returns boolean language sql stable security definer set search_path = ''
as $$ select exists (select 1 from public.recipes r where r.id = rid and r.user_id = auth.uid()) $$;

create or replace function public.owns_group(gid bigint)
returns boolean language sql stable security definer set search_path = ''
as $$ select exists (select 1 from public.recipe_groups g where g.id = gid and g.user_id = auth.uid()) $$;

create or replace function public.can_view_group(gid bigint)
returns boolean language sql stable security definer set search_path = ''
as $$
  select public.owns_group(gid)
      or exists (select 1 from public.collection_shares s where s.group_id = gid and s.friend_id = auth.uid())
$$;

create or replace function public.can_view_recipe(rid bigint)
returns boolean language sql stable security definer set search_path = ''
as $$
  select public.owns_recipe(rid)
      or exists (select 1 from public.recipe_shares s where s.recipe_id = rid and s.friend_id = auth.uid())
      or exists (
        select 1 from public.recipe_group_items i
        join public.collection_shares s on s.group_id = i.group_id
        where i.recipe_id = rid and s.friend_id = auth.uid()
      )
$$;

-- Has this person sent a friend request to you? (Request addresses are hidden from
-- everyone, so the profile rule asks through this helper.)
create or replace function public.asked_me(other uuid)
returns boolean language sql stable security definer set search_path = ''
as $$
  select exists (select 1 from public.friend_requests r where r.from_user = other and r.to_email = public.my_email())
$$;
revoke execute on function public.asked_me(uuid) from public, anon;
grant execute on function public.asked_me(uuid) to authenticated;

revoke execute on function public.is_friend(uuid), public.owns_recipe(bigint), public.owns_group(bigint),
  public.can_view_group(bigint), public.can_view_recipe(bigint), public.my_email() from public, anon;
grant execute on function public.is_friend(uuid), public.owns_recipe(bigint), public.owns_group(bigint),
  public.can_view_group(bigint), public.can_view_recipe(bigint), public.my_email() to authenticated;

-- ---------- Who may do what ----------
-- Signed-out visitors (anon) get nothing. Signed-in users change only their own rows,
-- and read their own rows plus what friends shared with them.

revoke all on public.recipes, public.recipe_ingredients, public.recipe_groups, public.recipe_group_items,
  public.recipe_profiles, public.friend_requests, public.friendships, public.recipe_shares, public.collection_shares
  from anon;
-- Supabase gives signed-in users every right on new tables by default; start from
-- nothing and grant only what the app uses, so a future policy mistake can't open more.
revoke all on public.recipes, public.recipe_ingredients, public.recipe_groups, public.recipe_group_items,
  public.recipe_profiles, public.friend_requests, public.friendships, public.recipe_shares, public.collection_shares
  from authenticated;
grant select, insert, update, delete on public.recipes, public.recipe_ingredients to authenticated;
grant select, insert, update, delete on public.recipe_groups to authenticated;
grant select, insert, delete on public.recipe_group_items to authenticated;
grant select on public.recipe_profiles to authenticated;
grant select, delete on public.friendships to authenticated;
-- Requests: never the address column. You see who sent you a request, and your own
-- sent list comes from list_sent_requests(), which hides addresses you didn't type.
grant select (id, from_user, to_user, created_at), delete on public.friend_requests to authenticated;
grant select, insert, delete on public.recipe_shares, public.collection_shares to authenticated;

