-- ---------- Friend actions ----------

-- Sends a request to an email address. Always ends the same way for the caller (no
-- hint whether the address has an account), except for clear mistakes like yourself.
-- If that person already asked you, you simply become friends.
create or replace function public.send_friend_request(email text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  me uuid := auth.uid();
  target text := lower(btrim(email));
  other uuid;
  reverse_id bigint;
begin
  if me is null then
    raise exception 'Sign in first.' using errcode = '42501';
  end if;
  if target is null or target !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' then
    raise exception 'That doesn''t look like an email address.' using errcode = '22023';
  end if;
  if target = public.my_email() then
    raise exception 'That''s your own email address.' using errcode = '22023';
  end if;
  if (select count(*) from public.friend_requests where from_user = me) >= 50 then
    raise exception 'You have 50 open requests. Wait for some answers first.' using errcode = '54000';
  end if;

  -- They asked you already: accept instead of sending a second request.
  select r.id, r.from_user into reverse_id, other
  from public.friend_requests r
  join public.recipe_profiles p on p.id = r.from_user
  where r.to_email = public.my_email() and p.email = target
  limit 1;
  if reverse_id is not null then
    insert into public.friendships (user_a, user_b) values (least(me, other), greatest(me, other))
      on conflict do nothing;
    delete from public.friend_requests where id = reverse_id;
    return;
  end if;

  -- Already friends: nothing to do (and nothing new learned).
  if exists (
    select 1 from public.friendships f join public.recipe_profiles p on p.id in (f.user_a, f.user_b)
    where me in (f.user_a, f.user_b) and p.id <> me and p.email = target
  ) then
    return;
  end if;

  insert into public.friend_requests (from_user, to_email) values (me, target)
    on conflict (from_user, to_email) do nothing;
end;
$$;

-- Accepts a request addressed to your email. Returns the new friend's id.
create or replace function public.accept_friend_request(request_id bigint)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  me uuid := auth.uid();
  sender uuid;
begin
  select from_user into sender from public.friend_requests
  where id = request_id and to_email = public.my_email();
  if sender is null then
    raise exception 'This request no longer exists.' using errcode = 'P0002';
  end if;
  insert into public.friendships (user_a, user_b) values (least(me, sender), greatest(me, sender))
    on conflict do nothing;
  delete from public.friend_requests where id = request_id;
  return sender;
end;
$$;

-- Your friends with their names, newest first.
create or replace function public.list_friends()
returns table (id uuid, display_name text, email text, since timestamptz)
language sql
stable
security definer
set search_path = ''
as $$
  select p.id, p.display_name, p.email, f.created_at
  from public.friendships f
  join public.recipe_profiles p on p.id = case when f.user_a = auth.uid() then f.user_b else f.user_a end
  where auth.uid() in (f.user_a, f.user_b)
  order by f.created_at desc
$$;

-- Ending a friendship also ends everything the two shared with each other.
create or replace function public.unshare_on_unfriend()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  delete from public.recipe_shares s using public.recipes r
  where r.id = s.recipe_id
    and ((r.user_id = old.user_a and s.friend_id = old.user_b) or (r.user_id = old.user_b and s.friend_id = old.user_a));
  delete from public.collection_shares s using public.recipe_groups g
  where g.id = s.group_id
    and ((g.user_id = old.user_a and s.friend_id = old.user_b) or (g.user_id = old.user_b and s.friend_id = old.user_a));
  return old;
end;
$$;

drop trigger if exists unshare_on_unfriend on public.friendships;
create trigger unshare_on_unfriend
  after delete on public.friendships
  for each row execute function public.unshare_on_unfriend();

-- Makes your own editable copy of a recipe you can see (for example one a friend shared).
create or replace function public.copy_recipe(source_id bigint)
returns bigint
language plpgsql
security invoker
set search_path = ''
as $$
declare
  new_id bigint;
begin
  insert into public.recipes (title, description, instructions, prep_time_minutes, cook_time_minutes, servings)
  select title, description, instructions, prep_time_minutes, cook_time_minutes, servings
  from public.recipes where id = source_id
  returning id into new_id;
  if new_id is null then
    raise exception 'Recipe not found.' using errcode = 'P0002';
  end if;
  insert into public.recipe_ingredients (recipe_id, position, name, quantity, unit)
  select new_id, position, name, quantity, unit from public.recipe_ingredients where recipe_id = source_id;
  return new_id;
end;
$$;

revoke execute on function public.send_friend_request(text), public.accept_friend_request(bigint),
  public.list_friends(), public.copy_recipe(bigint) from public, anon;
grant execute on function public.send_friend_request(text), public.accept_friend_request(bigint),
  public.list_friends(), public.copy_recipe(bigint) to authenticated;
revoke execute on function public.sync_recipe_profile(), public.unshare_on_unfriend() from public, anon, authenticated;

-- ---------- Saving a recipe with its ingredients in one step ----------
-- The app calls: supabase.rpc('save_recipe', {'recipe': {...}}). Returns the recipe id.
-- Runs with the caller's rights, so the rules above still apply.

create or replace function public.save_recipe(recipe jsonb)
returns bigint
language plpgsql
security invoker
set search_path = ''
as $$
declare
  rid bigint := nullif(recipe ->> 'id', '')::bigint;
begin
  if rid is null then
    insert into public.recipes (title, description, instructions, prep_time_minutes, cook_time_minutes, servings)
    values (
      recipe ->> 'title',
      nullif(btrim(recipe ->> 'description'), ''),
      nullif(btrim(recipe ->> 'instructions'), ''),
      (recipe ->> 'prep_time_minutes')::integer,
      (recipe ->> 'cook_time_minutes')::integer,
      (recipe ->> 'servings')::integer
    )
    returning id into rid;
  else
    update public.recipes set
      title             = recipe ->> 'title',
      description       = nullif(btrim(recipe ->> 'description'), ''),
      instructions      = nullif(btrim(recipe ->> 'instructions'), ''),
      prep_time_minutes = (recipe ->> 'prep_time_minutes')::integer,
      cook_time_minutes = (recipe ->> 'cook_time_minutes')::integer,
      servings          = (recipe ->> 'servings')::integer,
      updated_at        = now()
    where id = rid;
    if not found then
      raise exception 'Recipe not found.' using errcode = 'P0002';
    end if;
    delete from public.recipe_ingredients where recipe_id = rid;
  end if;

  insert into public.recipe_ingredients (recipe_id, position, name, quantity, unit)
  select rid, (i.ord - 1)::integer, btrim(i.item ->> 'name'),
         nullif(btrim(i.item ->> 'quantity'), ''), nullif(btrim(i.item ->> 'unit'), '')
  from jsonb_array_elements(coalesce(recipe -> 'ingredients', '[]'::jsonb)) with ordinality as i (item, ord)
  where btrim(coalesce(i.item ->> 'name', '')) <> '';

  return rid;
end;
$$;

revoke execute on function public.save_recipe(jsonb) from public, anon;
grant execute on function public.save_recipe(jsonb) to authenticated;

-- ---------- Keep-alive ----------
-- A free Supabase project pauses after about a week without activity.
-- A daily GitHub Action calls this (it reads no data).

create or replace function public.ping()
returns text
language sql
stable
